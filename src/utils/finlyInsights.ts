/** Card 0 — Primary: balance-range based */
function getPrimary(d: InsightInput): string {
  if (d.income === 0 && d.expenses === 0) return pick(BANKS.no_data, d);
  if (d.remaining < -3000) return pick(BANKS.deep_negative, d);
  if (d.remaining < -500) return pick(BANKS.medium_negative, d);
  if (d.remaining < 0) return pick(BANKS.small_negative, d);
  if (Math.abs(d.remaining) < 10) return pick(BANKS.zero, d);
  if (d.remaining < 1000) return pick(BANKS.low_positive, d);
  if (d.remaining < 4000) return pick(BANKS.moderate_positive, d);
  if (d.remaining < 10000) return pick(BANKS.strong_positive, d);
  return pick(BANKS.very_strong_positive, d);
}

/** Card 1 — Secondary: contextual overlay */
function getSecondary(d: InsightInput): string {
  // Savings opportunity: strong positive with a target set
  if (d.savingsTarget > 0 && d.remaining >= d.savingsTarget * 1.2) {
    return pick(BANKS.savings_opportunity, d);
  }
  // Savings encouragement even without explicit target when strong surplus
  if (d.remaining >= 5000) {
    return pick(BANKS.savings_opportunity, d);
  }
  // Heavy upcoming: upcoming expenses will significantly erode the balance
  if (d.upcomingExpenses > 0 && d.upcomingExpenses > Math.max(d.remaining * 0.5, 1000)) {
    return pick(BANKS.heavy_upcoming, d);
  }
  // Pending income waiting for confirmation
  if (d.pendingIncome > 0) {
    return pick(BANKS.pending_income, d);
  }
  // Moderate savings nudge
  if (d.remaining >= 2000) {
    return pick(BANKS.savings_opportunity, d);
  }
  return pick(BANKS.fallback_secondary, d);
}

/** Card 2 — Tertiary: temporal / carryover */
function getTertiary(d: InsightInput): string {
  // First 3 days of month — reference previous month result
  if (d.daysIntoMonth <= 3 && d.previousMonthRemaining !== undefined) {
    if (d.previousMonthRemaining > 100) return pick(BANKS.prev_positive, d);
    if (d.previousMonthRemaining < -100) return pick(BANKS.prev_negative, d);
  }
  // Last 7 days — month-end framing
  if (d.daysLeftInMonth <= 7) {
    return pick(BANKS.month_end, d);
  }
  return pick(BANKS.fallback_tertiary, d);
}

// ── Public API ────────────────────────────────────────────────────────────────

export function getInsightCards(d: InsightInput): [string, string, string] {
  return [getPrimary(d), getSecondary(d), getTertiary(d)];
}
