// ── Deterministic rotation ────────────────────────────────────────────────────

function pick(bank: string[], d: InsightInput): string {
  const idx = Math.abs(Math.round(d.income + d.expenses)) % bank.length;
  return bank[idx];
}

// ── Card 0: Current state ─────────────────────────────────────────────────────

function getStateCard(d: InsightInput): string {
  if (d.income === 0 && d.expenses === 0) return pick(BANKS.no_data, d);
  if (d.remaining < -3000) return pick(BANKS.deep_negative, d);
  if (d.remaining < -500) return pick(BANKS.medium_negative, d);
  if (d.remaining < 0) return pick(BANKS.small_negative, d);
  if (Math.abs(d.remaining) < 10) return pick(BANKS.zero, d);
  if (d.remaining < 1000) return pick(BANKS.low_positive, d);
  if (d.remaining < 4000) return pick(BANKS.moderate_positive, d);
  if (d.remaining < 10000) return pick(BANKS.strong_positive, d);
  return pick(BANKS.very_strong_positive, d);
}

// ── Card 1: Time context ──────────────────────────────────────────────────────

function getTimeCard(d: InsightInput): string {
  // Last 7 days: month-end framing
  if (d.daysLeftInMonth <= 7) {
    return pick(BANKS.month_end, d);
  }
  // First 3 days: reference previous month if available
  if (d.daysIntoMonth <= 3) {
    if (d.previousMonthRemaining !== undefined) {
      if (d.previousMonthRemaining > 100) return pick(BANKS.month_start_prev_good, d);
      if (d.previousMonthRemaining < -100) return pick(BANKS.month_start_prev_bad, d);
    }
    return pick(BANKS.month_start_fresh, d);
  }
  // Days 4–12: early month
  if (d.daysIntoMonth <= 12) {
    return pick(BANKS.month_early, d);
  }
  // Days 13–20: mid month
  return pick(BANKS.month_mid, d);
}

// ── Card 2: Savings / buffer / resilience ─────────────────────────────────────

function getSavingsCard(d: InsightInput): string {
  // Negative or very tight: protect first
  if (d.remaining < 200) {
    return pick(BANKS.savings_tight, d);
  }
  // Heavy upcoming obligations will eat most of remaining
  if (d.upcomingExpenses > 0 && d.upcomingExpenses > Math.max(d.remaining * 0.5, 1000)) {
    return pick(BANKS.savings_buffer_warning, d);
  }
  // No savings target set
  if (d.savingsTarget === 0) {
    // Only nudge if there's actual room
    if (d.remaining >= 500) return pick(BANKS.savings_no_target, d);
    return pick(BANKS.savings_tight, d);
  }
  // Strong surplus vs savings target
  if (d.remaining >= d.savingsTarget * 1.3 || d.remaining >= 6000) {
    return pick(BANKS.savings_strong, d);
  }
  // Some room to save
  if (d.remaining >= 1000) {
    return pick(BANKS.savings_encourage, d);
  }
  return pick(BANKS.savings_tight, d);
}

// ── Public API ────────────────────────────────────────────────────────────────

/** Returns [stateCard, timeCard, savingsCard] */
export function getInsightCards(d: InsightInput): [string, string, string] {
  return [getStateCard(d), getTimeCard(d), getSavingsCard(d)];
}
